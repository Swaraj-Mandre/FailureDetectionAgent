"""Makes three small made-up shops to try the + button with, in the shapes shops really have.

    python data/make_sample_uploads.py

kirana_sale_report.xlsx   one sheet like a billing app exports: shop name on top, rupee text, a total row
medical_*.csv             two CSV files that belong together (stock and bills)
garments.sql              a MySQL dump like phpMyAdmin exports, three linked tables

The numbers are fixed by a seed, so the answers are the same every time.
"""
import csv
import random
from pathlib import Path

import openpyxl

OUT = Path(__file__).resolve().parent / "sample_uploads"


def kirana(rng):
    items = {"Aashirvaad Atta 5kg": 265, "Tata Salt 1kg": 28, "Fortune Oil 1L": 155,
             "Parle-G 800g": 90, "Surf Excel 1kg": 140, "Maggi 12 pack": 168}
    parties = {"Cash Sale": "", "Ramesh Patil": "9800000001", "Sunita Joshi": "9800000002",
               "Hotel Annapurna": "9800000003"}
    book = openpyxl.Workbook()
    sheet = book.active
    sheet.title = "Sale Report"
    sheet.append(["Shree Ganesh Kirana Stores"])
    sheet.append(["Sale Report", None, "From 01/07/2026 To 30/09/2026"])
    sheet.append([])
    sheet.append(["Date", "Invoice No.", "Party Name", "Party Phone No.", "Item Name", "Qty", "Rate", "Amount",
                  "Payment Type", "Balance Due"])
    invoice, total, due_total = 1000, 0, 0
    for month in (7, 8, 9):
        for day in range(1, 29):
            invoice += 1
            party, pay = rng.choice(list(parties)), rng.choice(["Cash", "UPI", "Credit"])
            for item in rng.sample(list(items), 2):
                qty = rng.randint(1, 6)
                amount = qty * items[item]
                due = amount if pay == "Credit" else 0
                total, due_total = total + amount, due_total + due
                sheet.append([f"{day:02}/{month:02}/2026", invoice, party, parties[party], item, qty,
                              f"₹ {items[item]:,.2f}", f"₹ {amount:,.2f}", pay, f"₹ {due:,.2f}"])
    sheet.append(["Total", None, None, None, None, None, None, f"₹ {total:,.2f}", None, f"₹ {due_total:,.2f}"])
    sheet.append(["Generated by billing app"])
    book.save(OUT / "kirana_sale_report.xlsx")


def medical(rng):
    medicines = [("Dolo 650", "Micro Labs", 30), ("Crocin", "GSK", 25), ("Azithral 500", "Alembic", 120),
                 ("Pan 40", "Alkem", 155), ("Shelcal", "Torrent", 130), ("Allegra 120", "Sanofi", 230)]
    with open(OUT / "medical_stock.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["Medicine", "Company", "Batch No", "Expiry Date", "Stock Qty", "Purchase Price", "MRP"])
        for i, (name, company, mrp) in enumerate(medicines):
            w.writerow([name, company, f"00{i}91", f"28-{(i * 2) % 12 + 1:02}-{2026 + i % 2}", rng.randint(3, 90),
                        round(mrp * 0.7, 2), mrp])
    with open(OUT / "medical_bills.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f, delimiter=";")
        w.writerow(["Bill No", "Bill Date", "Medicine", "Qty", "Total"])
        for bill in range(1, 121):
            name, _, mrp = rng.choice(medicines)
            qty = rng.randint(1, 5)
            w.writerow([bill, f"{rng.randint(1, 28):02}-{rng.choice([8, 9, 10]):02}-2026", name, qty,
                        f"{qty * mrp:,.2f}"])


def garments(rng):
    suppliers = [(1, "Shree Textiles", "Surat"), (2, "Laxmi Fabrics", "Ichalkaranji"), (3, "Om Garments", "Mumbai")]
    items = [(1, r"Men\'s Cotton Kurta", "M", 1, 650), (2, "Silk Saree", "Free", 2, 2400),
             (3, "Denim Jeans", "32", 3, 1100), (4, "Drop Shoulder T-shirt", "L", 3, 420), (5, "Dupatta", "Free", 1, 300)]
    supplier_rows = ",\n".join(f"({i}, '{n}', '{t}', '980000001{i}')" for i, n, t in suppliers)
    item_rows = ",\n".join(f"({i}, '{d}', '{s}', {sup}, '{p:.2f}', '{p * 0.6:.2f}')" for i, d, s, sup, p in items)
    sale_rows = ",\n".join(
        f"({i}, '2026-{rng.choice([8, 9, 10]):02}-{rng.randint(1, 28):02} 11:30:00', {rng.randint(1, 5)}, "
        f"{rng.randint(1, 4)}, {1 if rng.random() < 0.1 else 0})" for i in range(1, 151))
    (OUT / "garments.sql").write_text(f"""-- phpMyAdmin SQL Dump
SET SQL_MODE = "NO_AUTO_VALUE_ON_ZERO";
/*!40101 SET NAMES utf8mb4 */;

DROP TABLE IF EXISTS `tbl_supplier`;
CREATE TABLE `tbl_supplier` (
  `sup_id` int(11) NOT NULL,
  `sup_name` varchar(60) DEFAULT NULL,
  `town` varchar(40) DEFAULT NULL,
  `mobile` varchar(15) DEFAULT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
INSERT INTO `tbl_supplier` (`sup_id`, `sup_name`, `town`, `mobile`) VALUES
{supplier_rows};

CREATE TABLE `tbl_item` (
  `itm_id` int(11) NOT NULL,
  `itm_desc` varchar(80),
  `size` varchar(10),
  `sup_id` int(11),
  `sell_price` decimal(10,2),
  `cost_price` decimal(10,2)
) ENGINE=InnoDB;
INSERT INTO `tbl_item` VALUES
{item_rows};

CREATE TABLE `tbl_sale` (
  `sale_id` int(11) NOT NULL,
  `sale_dt` datetime,
  `itm_id` int(11),
  `pcs` int(11),
  `returned` tinyint(1)
) ENGINE=InnoDB;
INSERT INTO `tbl_sale` (`sale_id`, `sale_dt`, `itm_id`, `pcs`, `returned`) VALUES
{sale_rows};

ALTER TABLE `tbl_item` ADD PRIMARY KEY (`itm_id`), ADD KEY `sup_id` (`sup_id`);
ALTER TABLE `tbl_item` ADD CONSTRAINT `f1` FOREIGN KEY (`sup_id`) REFERENCES `tbl_supplier` (`sup_id`);
ALTER TABLE `tbl_sale` ADD CONSTRAINT `f2` FOREIGN KEY (`itm_id`) REFERENCES `tbl_item` (`itm_id`);
COMMIT;
""", encoding="utf-8", newline="\n")


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    kirana(random.Random(7))
    medical(random.Random(8))
    garments(random.Random(9))
    print("Made:", ", ".join(sorted(p.name for p in OUT.iterdir())))
